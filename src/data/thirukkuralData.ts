// Helper to extract words array from line1 and line2 (line1: 4 words, line2: 3 words)
export function getKuralWords(kural: ThirukkuralItem): string[] {
  const line1Words = kural.line1.trim().split(/\s+/);
  const line2Words = kural.line2.trim().split(/\s+/);
  return [...line1Words, ...line2Words];
}

// Generate distractor words exclusively from other verified Thirukkurals in the dataset
export function getDistractorWords(correctWords: string[], count: number): string[] {
  const allWords = new Set<string>();
  THIRUKKURAL_DATASET.forEach((k) => {
    getKuralWords(k).forEach((w) => {
      if (!correctWords.includes(w)) {
        allWords.add(w);
      }
    });
  });

  const array = Array.from(allWords);
  // Shuffle deterministically / randomly
  const shuffled = [...array].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
